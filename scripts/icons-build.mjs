/**
 * Material Symbols -> src/ui/primitives/symbols.generated.ts (named exports,
 * so a page only ships the icons it draws).
 *
 *   npm run icons:build            write the module
 *   npm run icons:build -- --check fail if it is out of date
 *
 * Want another icon? Add `"YourName": "material_symbol_name"` to
 * scripts/icon-map.json (names: https://fonts.google.com/icons), then:
 *   npm i --no-save @material-symbols/svg-400@0.47.5   (the 3,900 source SVGs, ~40 MB, once)
 *   npm run icons:build
 * Every icon here is Material Symbols Rounded 400, Apache-2.0.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const SRC = process.env.ICONS_SRC ?? resolve("node_modules/@material-symbols/svg-400/rounded");
const OUT = resolve(process.env.ICONS_OUT ?? "ui/primitives/symbols.generated.ts");
const MAP = resolve("scripts/icon-map.json");

const pathOf = (file) => {
    const all = [...readFileSync(file, "utf8").matchAll(/\sd="([^"]+)"/g)].map((m) => m[1]);
    if (!all.length) throw new Error(`no path in ${file}`);
    return all.join(" ");
};

if (!existsSync(SRC)) { console.error("🔴 No icon sources. Run: npm i --no-save @material-symbols/svg-400@0.47.5"); process.exit(1); }
const entries = Object.entries(JSON.parse(readFileSync(MAP, "utf8"))).filter(([k]) => !k.startsWith("_"));
const lines = [
    "/* GENERATED by scripts/icons-build.mjs — do not edit.",
    " * Material Symbols Rounded 400, Apache-2.0. Run `npm run icons:build`.",
    " */",
    "",
    "/** One symbol: the outlined path, and the filled one where it differs. */",
    "export type Glyph = { d: string; f?: string; n: string };",
    "",
    'export const SYMBOL_VIEWBOX = "0 -960 960 960";',
    "",
];
const missing = [];
for (const [name, symbol] of entries) {
    const base = resolve(SRC, `${symbol}.svg`);
    if (!existsSync(base)) { missing.push(`${name} -> ${symbol}`); continue; }
    const d = pathOf(base);
    const fill = resolve(SRC, `${symbol}-fill.svg`);
    const f = existsSync(fill) ? pathOf(fill) : null;
    lines.push(`export const ${name}: Glyph = { n: ${JSON.stringify(symbol)}, d: ${JSON.stringify(d)}${f && f !== d ? `, f: ${JSON.stringify(f)}` : ""} };`);
}
if (missing.length) { console.error("🔴 icon-map.json names symbols that don't exist:\n  " + missing.join("\n  ")); process.exit(1); }
const out = lines.join("\n") + "\n";
if (process.argv.includes("--check")) {
    if ((existsSync(OUT) ? readFileSync(OUT, "utf8") : "") !== out) { console.error("🔴 symbols.generated.ts is stale: run npm run icons:build"); process.exit(1); }
    console.log(`✅ icons: ${entries.length}, up to date`);
} else {
    writeFileSync(OUT, out);
    console.log(`✅ icons: wrote ${entries.length} (${(out.length / 1024).toFixed(0)} KB raw)`);
}
